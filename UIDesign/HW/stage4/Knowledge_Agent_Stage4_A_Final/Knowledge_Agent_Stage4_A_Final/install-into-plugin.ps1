param(
  [string]$TargetManifest,
  [switch]$Quiet
)
$ErrorActionPreference = 'Stop'
if (-not $TargetManifest) {
  Add-Type -AssemblyName System.Windows.Forms
  $dialog = New-Object System.Windows.Forms.OpenFileDialog
  $dialog.Title = 'Select manifest.json from the new empty Figma plugin'
  $dialog.Filter = 'Figma plugin manifest (manifest.json)|manifest.json'
  if ($dialog.ShowDialog() -ne [System.Windows.Forms.DialogResult]::OK) { exit 0 }
  $TargetManifest = $dialog.FileName
}
$resolvedManifest = (Resolve-Path -LiteralPath $TargetManifest).Path
$pluginFolder = [System.IO.Path]::GetDirectoryName($resolvedManifest)
$manifest = Get-Content -LiteralPath $resolvedManifest -Raw -Encoding UTF8 | ConvertFrom-Json
if (-not $manifest.id) { throw 'Select the manifest generated by Figma New Plugin. A real plugin ID is required.' }
foreach ($file in @('code.js','ui.html')) {
  if (-not (Test-Path -LiteralPath (Join-Path $PSScriptRoot $file) -PathType Leaf)) { throw ('Missing final package file: ' + $file) }
}
$backupFolder = Join-Path $pluginFolder ('backup-before-A-final-' + (Get-Date -Format 'yyyyMMdd-HHmmss-fff'))
New-Item -ItemType Directory -Path $backupFolder | Out-Null
foreach ($file in @('manifest.json','code.js','ui.html')) {
  $existingFile = Join-Path $pluginFolder $file
  if (Test-Path -LiteralPath $existingFile -PathType Leaf) { Copy-Item -LiteralPath $existingFile -Destination (Join-Path $backupFolder $file) }
}
foreach ($file in @('code.js','ui.html')) {
  $sourceFile = Join-Path $PSScriptRoot $file
  $targetFile = Join-Path $pluginFolder $file
  if (-not [StringComparer]::OrdinalIgnoreCase.Equals($sourceFile,$targetFile)) { Copy-Item -LiteralPath $sourceFile -Destination $targetFile -Force }
}
$updates = @{
  name = 'Knowledge Agent - A Final - Segoe UI'
  api = '1.0.0'
  main = 'code.js'
  ui = 'ui.html'
  editorType = @('figma')
  documentAccess = 'dynamic-page'
  networkAccess = @{ allowedDomains = @('none') }
}
foreach ($key in $updates.Keys) { $manifest | Add-Member -MemberType NoteProperty -Name $key -Value $updates[$key] -Force }
$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($resolvedManifest, ($manifest | ConvertTo-Json -Depth 8), $utf8)
Write-Output ('Installed: ' + $resolvedManifest)
Write-Output ('Backup: ' + $backupFolder)
if (-not $Quiet) {
  Add-Type -AssemblyName System.Windows.Forms
  [System.Windows.Forms.MessageBox]::Show('Installed. Return to Figma > Plugins > Development, run the new plugin, then click Generate.','Knowledge Agent A Final') | Out-Null
}
