def mr(text):
    r = OxmlElement('m:r')
    t = OxmlElement('m:t')
    t.text = text
    r.append(t)
    return r

def frac(num, den):
    f = OxmlElement('m:f')
    for tag, text in [('m:num', num), ('m:den', den)]:
        e = OxmlElement(tag)
        e.append(mr(text))
        f.append(e)
    return f

def summation(low, high, content):
    s = OxmlElement('m:nary')
    pr = OxmlElement('m:naryPr')
    ch = OxmlElement('m:chr'); ch.set(qn('m:val'), '∑'); pr.append(ch)
    loc = OxmlElement('m:limLoc'); loc.set(qn('m:val'), 'subSup'); pr.append(loc)
    s.append(pr)
    for tag, text in [('m:sub', low), ('m:sup', high)]:
        e = OxmlElement(tag); e.append(mr(text)); s.append(e)
    e = OxmlElement('m:e')
    e.append(content if not isinstance(content, str) else mr(content))
    s.append(e)
    return s

